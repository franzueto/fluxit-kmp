import ComposeApp
import FirebaseAuth
import FirebaseCore
import FirebaseFirestore
import FirebaseStorage
import UIKit

/// FB-007 initialization seam for the official Firebase Apple SDK.
///
/// This is deliberately the only place in the iOS app that touches Firebase SDK
/// types during Phase 0. It mirrors `AndroidFirebaseInitializer` in `androidMain`:
/// configure the default app, then - only when the build enabled it - point
/// Auth/Firestore/Storage at the local emulator suite.
///
/// The Apple SDK is integrated through Swift Package Manager into the Xcode
/// project rather than through Kotlin/Native cinterop, because `FirebaseStorage`
/// and the modern `FirebaseAuth` are Swift modules that cinterop cannot consume.
/// The emulator endpoints still come from the single shared source of truth: the
/// `FirebaseEmulatorConfig` constants generated by
/// `:composeApp:generateFirebaseEmulatorConfig`, surfaced to Swift through
/// `IosFirebaseEmulatorSettings` in `iosMain`.
///
/// `FB-103` added the second responsibility below: registering the Swift
/// implementation of the Kotlin `IosAuthBridge` protocol, which is how the
/// Firebase-neutral `AuthRepository` reaches Auth on iOS (PLAN-008). Phase 2 does
/// the same for Firestore/Storage.
enum FirebaseBootstrap {

    private static var initialized = false

    /// Initializes the default `FirebaseApp` from the bundled
    /// `GoogleService-Info.plist` (gitignored, per `DEC-002b`).
    ///
    /// Must run before anything else touches the Firebase SDK, because
    /// `useEmulator` may only be called before a service instance is used.
    /// `AppDelegate.application(_:didFinishLaunchingWithOptions:)` is the earliest
    /// point the system gives us and runs strictly before any SwiftUI scene or
    /// view body - and therefore before `ContentView` creates the Compose view
    /// controller that starts Koin.
    static func start() {
        guard !initialized else { return }
        initialized = true

        guard FirebaseOptions.defaultOptions() != nil else {
            fatalError(
                "Firebase default app could not be initialized. "
                + "iosApp/GoogleService-Info.plist is missing from the app bundle; "
                + "fetch it from the Firebase Console (it is gitignored)."
            )
        }
        FirebaseApp.configure()

        if IosFirebaseEmulatorSettings.shared.enabled {
            connectToEmulators()
        }

        // FB-103: hand the Swift Auth implementation to the Kotlin framework. This runs
        // inside `didFinishLaunchingWithOptions`, strictly before `ContentView` creates
        // the Compose view controller that starts Koin, so the `single<AuthRepository>`
        // binding in `platformModule()` can never be resolved before the bridge exists.
        IosAuthBridgeRegistry.shared.register(bridge: FirebaseAuthBridge())
    }

    /// FB-103 evidence hook: runs the emulator-backed Auth integration check and prints
    /// its report, then leaves the app running normally.
    ///
    /// Two independent gates keep this out of any ordinary build: the app must be
    /// launched with `-FluxItAuthSelfCheck`, and the Kotlin check itself refuses to run
    /// unless the build was configured with `fluxit.firebase.emulator.enabled=true`,
    /// which is the same flag that points Auth at the local emulator. It therefore
    /// cannot touch the live development project.
    static func runAuthSelfCheckIfRequested() {
        let arguments = ProcessInfo.processInfo.arguments
        let restorationPhase = arguments.contains("-FluxItAuthRestorePrepare") ? "prepare"
            : arguments.contains("-FluxItAuthRestoreVerify") ? "verify"
            : nil

        guard arguments.contains("-FluxItAuthSelfCheck") || restorationPhase != nil else { return }

        Task {
            do {
                let report: String
                if let phase = restorationPhase {
                    report = try await IosAuthIntegrationCheck.shared.runRestorationPhase(phase: phase)
                } else {
                    report = try await IosAuthIntegrationCheck.shared.run()
                }
                print(report)
            } catch {
                print("FB-103 iOS Auth integration check: THREW \(error)")
                print("FB-103 END")
            }
        }
    }

    private static func connectToEmulators() {
        // Passed through verbatim: the iOS simulator shares the host network stack,
        // so no Android-style 10.0.2.2 loopback translation applies here.
        let settings = IosFirebaseEmulatorSettings.shared
        let host = settings.host

        Auth.auth().useEmulator(withHost: host, port: Int(settings.authPort))
        // `useEmulator` also disables TLS on the Firestore client; it must be called
        // before the first `Firestore` operation or the SDK throws.
        Firestore.firestore().useEmulator(withHost: host, port: Int(settings.firestorePort))
        Storage.storage().useEmulator(withHost: host, port: Int(settings.storagePort))
    }
}

/// Minimal application delegate whose only job is to give `FirebaseApp.configure()`
/// a deterministic home. `iOSApp.swift` is a bare SwiftUI `@main` with no delegate,
/// so this is attached via `@UIApplicationDelegateAdaptor`. Firebase documents this
/// as the SwiftUI integration point, and later Firebase features that need UIKit
/// app-lifecycle callbacks (push notifications, phone auth) already have a home here.
final class AppDelegate: NSObject, UIApplicationDelegate {
    func application(
        _ application: UIApplication,
        didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
    ) -> Bool {
        FirebaseBootstrap.start()
        FirebaseBootstrap.runAuthSelfCheckIfRequested()
        return true
    }
}
